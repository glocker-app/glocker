## Generic Source Update Logic

def get_source_by_id(source_id: int) -> Optional[Dict]:
    """Get source definition by ID."""
    for source in SOURCES:
        if source['id'] == source_id:
            return source
    return None


def update_source(source_id: int) -> str:
    """
    Update domains from a specific source.
    Returns: 'updated', 'skipped', or raises SystemExit on error
    """
    # Step 1: Find source
    source = get_source_by_id(source_id)
    if not source:
        print(f"Error: Source ID {source_id} not found", file=sys.stderr)
        print("\nAvailable sources:")
        list_sources()
        sys.exit(1)

    print(f"\nUpdating source [{source['id']}]: {source['name']}")
    print(f"Description: {source['description']}\n")

    # Step 2: Idempotency — skip if the source's conf.d file is already current.
    existing_timestamp = read_source_timestamp(confd_path(source))

    # Step 3: Fetch latest data from source
    fetch_func = source['fetch_func']
    domains, timestamp, metadata = fetch_func()

    if existing_timestamp and existing_timestamp == timestamp:
        print(f"\n  Already up to date (last update: {timestamp})")
        ensure_include(source)  # self-heal the include even when nothing was re-downloaded
        return 'skipped'
    if existing_timestamp:
        print("  Update available, proceeding...")
    else:
        print("  First run for this source...")

    # Step 7: Strip www prefix, apply exclusions, and remove duplicates
    print(f"  Processing {len(domains)} domains...")
    original_count = len(domains)

    # Strip www. prefix from all domains
    stripped_domains = []
    for domain in domains:
        if domain.startswith('www.'):
            stripped_domains.append(domain[4:])  # Remove 'www.' prefix
        else:
            stripped_domains.append(domain)

    # Apply exclusion list
    excluded_count = 0
    filtered_domains = []
    for domain in stripped_domains:
        domain_lower = domain.lower()
        if any(substr in domain_lower for substr in EXCLUDED_DOMAIN_SUBSTRINGS):
            excluded_count += 1
        else:
            filtered_domains.append(domain)
    if excluded_count > 0:
        print(f"  Excluded {excluded_count} domains matching exclusion list")

    # Drop anything the user maintains by hand, and its subdomains, so a
    # hand-listed domain (e.g. one marked unblockable) never also appears as a
    # permanent-block entry from a fetched list.
    manual = get_manual_domains()
    manual_skipped = 0
    if manual:
        kept = []
        for domain in filtered_domains:
            if covered_by_manual(domain.lower(), manual):
                manual_skipped += 1
            else:
                kept.append(domain)
        filtered_domains = kept
        if manual_skipped > 0:
            print(f"  Skipped {manual_skipped} domains covered by {len(manual)} manual entries")

    # Remove duplicates while preserving order
    seen = set()
    unique_domains = []
    for domain in filtered_domains:
        if domain not in seen:
            seen.add(domain)
            unique_domains.append(domain)

    removed_count = original_count - len(unique_domains) - excluded_count - manual_skipped
    if removed_count > 0:
        print(f"  Removed {removed_count} duplicate/www-prefixed domains")

    # Format domains using source's parse function
    parse_func = source['parse_func']
    formatted_lines = [parse_func(domain) for domain in unique_domains]
    formatted_domains = '\n'.join(formatted_lines)

    # Step 4: Write the source's conf.d file.
    path = confd_path(source)
    print(f"  Writing {path}...")
    try:
        write_source_file(source, formatted_domains, timestamp, len(unique_domains))
        ensure_include(source)  # wire it into conf.yaml if it isn't already
        print(f"  Successfully wrote {len(unique_domains)} domains\n")
        return 'updated'
    except Exception as e:
        print(f"  Error writing {path}: {e}", file=sys.stderr)
        sys.exit(1)

## Strip Managed Sources

def strip_managed_sources():
    """Delete every generated conf.d/ blocklist file AND its `!include` line in
    conf.yaml (so nothing is left pointing at a deleted file). The hand-maintained
    conf.d/domains-personal.yaml and its include are untouched."""
    print("\nRemoving all generated blocklist files from conf.d/...\n")

    removed_sources = []
    for source in SOURCES:
        path = confd_path(source)
        removed_include = remove_include(source)  # unwire from conf.yaml either way
        try:
            os.remove(path)
        except FileNotFoundError:
            continue
        except Exception as e:
            print(f"  Error removing {path}: {e}", file=sys.stderr)
            sys.exit(1)
        removed_sources.append(source['name'])
        print(f"  ✓ Removed: {path}")
        _ = removed_include

    if not removed_sources:
        print("  No generated blocklist files found.\n")
        return

    print(f"\n  Removed {len(removed_sources)} generated blocklist file(s).")
    print("  The personal list (conf.d/domains-personal.yaml) is untouched.\n")

## Source Listing
def list_sources():
    """Display all available sources with their current status."""
    print("\nAvailable domain sources:\n")

    for source in SOURCES:
        print(f"  [{source['id']}] {source['name']}")
        print(f"      {source['description']}")

        path = confd_path(source)
        try:
            with open(path, 'r') as f:
                head = f.read(4096)
        except FileNotFoundError:
            print("      Status: Not yet generated (first run)")
            print(f"      File:   {path}")
            print()
            continue

        ts = re.search(r'# Last updated: ([0-9T:\-Z]+)', head)
        cnt = re.search(r'\((\d+) domains\)', head)
        if ts and cnt:
            print(f"      Last updated: {ts.group(1)} ({cnt.group(1)} domains)")
        elif ts:
            print(f"      Last updated: {ts.group(1)}")
        else:
            print("      Status: Generated (no header timestamp)")
        print(f"      File:   {path}")
        print()

    print("Usage:")
    print("  ./update_domains.py <number>  - Update a specific source")
    print("  ./update_domains.py all       - Update all sources")
    print("  ./update_domains.py strip     - Remove all managed sources\n")

