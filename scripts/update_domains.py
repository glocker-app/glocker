#!/usr/bin/env python3
"""
Multi-source domain list updater for glocker config file.

This script supports updating domain blocklists from multiple sources,
each with custom fetching and parsing logic. The script is idempotent
and checks timestamps to avoid redundant updates.

Usage:
    ./update_domains.py          - List all available sources
    ./update_domains.py <id>     - Update from specific source
    ./update_domains.py all      - Update from all sources sequentially
    ./update_domains.py strip    - Remove all managed sources (keeps manual domains)
"""

import json
import os
import re
import sys
import time
import urllib.request
from typing import Optional, Tuple, List, Dict, Callable

# Constants
CONFIG_FILE = "conf/conf.yaml"
# Each source's blocklist is generated into its own file here and pulled into
# conf.yaml with `!include conf.d/<file>`. Keeping the big lists out of conf.yaml
# keeps the hand-edited config small.
CONFD_DIR = "conf/conf.d"
# How often to print a download-progress line during a fetch.
PROGRESS_INTERVAL_SECONDS = 5

# Domains containing any of these substrings (case-insensitive) will be excluded
# from all sources during processing.
EXCLUDED_DOMAIN_SUBSTRINGS = [
    "mullvad",
    "customeriomail.com",
]

# Domains the user maintains by hand (the non-generated conf.d files, e.g. the
# personal list). Every fetched blocklist is filtered so none of these — or their
# subdomains — slip in as a second entry. Without this, a hand-listed domain
# marked `unblockable` still can't be unblocked: the duplicate blocklist entry
# (not unblockable) re-blocks it on the next enforcement pass.
MANUAL_FILE_MARKER = "Generated by update_domains.py"
_MANUAL_NAME_RE = re.compile(r'^\s*-?\s*name:\s*["\']?([^"\'\s#]+)')
_manual_domains_cache: Optional[set] = None


def _names_from_file(path: str) -> set:
    """Domain `name:` values from a hand-maintained conf file. A file this script
    generated (its header carries MANUAL_FILE_MARKER) is skipped — its entries are
    blocklist output, not manual input."""
    try:
        with open(path) as f:
            text = f.read()
    except OSError:
        return set()
    if MANUAL_FILE_MARKER in text:
        return set()
    return {m.group(1).lower() for line in text.splitlines()
            if (m := _MANUAL_NAME_RE.match(line))}


def get_manual_domains() -> set:
    """Hand-listed domain names, read once from the non-generated conf.d files.
    conf.yaml itself is intentionally skipped: its `name:` keys also cover
    forbidden programs, which must not be mistaken for domains."""
    global _manual_domains_cache
    if _manual_domains_cache is None:
        manual = set()
        if os.path.isdir(CONFD_DIR):
            for fn in sorted(os.listdir(CONFD_DIR)):
                if fn.endswith((".yaml", ".yml")):
                    manual |= _names_from_file(os.path.join(CONFD_DIR, fn))
        _manual_domains_cache = manual
    return _manual_domains_cache


def covered_by_manual(domain: str, manual: set) -> bool:
    """True if `domain` equals, or is a subdomain of, a hand-listed name."""
    parts = domain.split(".")
    return any(".".join(parts[i:]) in manual for i in range(len(parts)))


## Utility Functions

def fetch_url(url: str) -> bytes:
    """Fetch content from a URL, printing a progress line every few seconds so a
    multi-MB blocklist download doesn't look hung."""
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            total = int(response.headers.get("Content-Length") or 0)
            chunks = []
            downloaded = 0
            last = time.monotonic()
            while True:
                chunk = response.read(65536)
                if not chunk:
                    break
                chunks.append(chunk)
                downloaded += len(chunk)
                if time.monotonic() - last >= PROGRESS_INTERVAL_SECONDS:
                    last = time.monotonic()
                    kb = downloaded // 1024
                    if total:
                        pct = downloaded * 100 // total
                        print(f"    ...{pct:3d}%  ({kb:,} / {total // 1024:,} KB)", flush=True)
                    else:
                        print(f"    ...{kb:,} KB downloaded", flush=True)
            return b"".join(chunks)
    except Exception as e:
        print(f"Error fetching {url}: {e}", file=sys.stderr)
        sys.exit(1)


def confd_path(source: Dict) -> str:
    """Path to a source's generated blocklist file under conf.d/."""
    return os.path.join(CONFD_DIR, source['file'])


def include_marker(source: Dict) -> str:
    """The `!include conf.d/<file>` reference for a source (matched as a substring)."""
    return f"!include conf.d/{source['file']}"


def ensure_include(source: Dict) -> bool:
    """Make sure conf.yaml pulls this source in via `!include conf.d/<file>`.

    Idempotent: does nothing if the line is already there. Text-based on purpose —
    conf.yaml uses the custom !include tag, which a YAML round-trip would mangle.
    Inserts inside the `domains:` block, after the last existing include (or right
    after `domains:` if there are none). Returns True if it added the line.
    """
    marker = include_marker(source)
    with open(CONFIG_FILE) as f:
        lines = f.read().split('\n')
    if any(marker in ln for ln in lines):
        return False

    domains_idx = next((i for i, ln in enumerate(lines) if ln.rstrip() == 'domains:'), None)
    if domains_idx is None:
        print(f"  WARN: no 'domains:' section in {CONFIG_FILE}; not adding include "
              f"for {source['name']}", file=sys.stderr)
        return False

    # Stay inside the domains: block (stop at the next column-0 key) and land
    # after the last existing include so they group together in order.
    insert_at = domains_idx + 1
    for i in range(domains_idx + 1, len(lines)):
        if re.match(r'^[A-Za-z_]', lines[i]):
            break
        if '!include conf.d/domains-' in lines[i]:
            insert_at = i + 1

    lines.insert(insert_at, f"  - {marker}")
    with open(CONFIG_FILE, 'w') as f:
        f.write('\n'.join(lines))
    print(f"  + wired {source['file']} into {CONFIG_FILE} via !include")
    return True


def remove_include(source: Dict) -> bool:
    """Remove a source's `!include` line from conf.yaml — the mirror of
    ensure_include, so stripping a source never leaves conf.yaml pointing at a
    file that's just been deleted. Returns True if it removed a line."""
    marker = include_marker(source)
    with open(CONFIG_FILE) as f:
        lines = f.read().split('\n')
    kept = [ln for ln in lines if marker not in ln]
    if len(kept) == len(lines):
        return False
    with open(CONFIG_FILE, 'w') as f:
        f.write('\n'.join(kept))
    print(f"  - removed {source['file']} !include from {CONFIG_FILE}")
    return True


def read_source_timestamp(path: str) -> Optional[str]:
    """Read the '# Last updated: TIMESTAMP' header from a conf.d file (for the
    idempotency check). Returns None if the file is absent or has no header."""
    try:
        with open(path, 'r') as f:
            head = f.read(4096)
    except FileNotFoundError:
        return None
    match = re.search(r'# Last updated: ([0-9T:\-Z]+)', head)
    return match.group(1) if match else None


def write_source_file(source: Dict, formatted_domains: str, timestamp: str, count: int) -> None:
    """Write one source's blocklist to its conf.d file as a standalone YAML
    sequence, with a header recording the source and update time. conf.yaml pulls
    it in via `!include conf.d/<file>`."""
    os.makedirs(CONFD_DIR, exist_ok=True)
    header = (
        f"{source['marker']}. Blocked 24/7\n"
        f"# Last updated: {timestamp} ({count} domains)\n"
        f"# Generated by update_domains.py — do not edit; pulled into conf.yaml via !include.\n"
        f"\n"
    )
    with open(confd_path(source), 'w') as f:
        f.write(header)
        f.write(formatted_domains)
        f.write("\n")

## Source-Specific Functions: Bon Appetit Porn Domains

def fetch_bon_appetit() -> Tuple[List[str], str, Dict]:
    """
    Fetch Bon Appetit porn domains list.
    Returns: (domains_list, timestamp, metadata_dict)
    """
    META_URL = "https://raw.githubusercontent.com/Bon-Appetit/porn-domains/refs/heads/main/meta.json"
    BASE_URL = "https://raw.githubusercontent.com/Bon-Appetit/porn-domains/refs/heads/main/"

    # Step 1: Fetch metadata
    print("  Fetching metadata...")
    content = fetch_url(META_URL)

    try:
        meta = json.loads(content.decode('utf-8'))
    except json.JSONDecodeError as e:
        print(f"  Error parsing meta.json: {e}", file=sys.stderr)
        sys.exit(1)

    # Extract blocklist info
    if 'blocklist' not in meta:
        print("  Error: 'blocklist' not found in meta.json", file=sys.stderr)
        sys.exit(1)

    blocklist = meta['blocklist']
    filename = blocklist.get('name')
    timestamp = blocklist.get('updated')
    lines_count = blocklist.get('lines', 0)

    if not filename or not timestamp:
        print("  Error: Missing required fields in blocklist metadata", file=sys.stderr)
        sys.exit(1)

    print(f"  Current blocklist: {filename}")
    print(f"  Last updated: {timestamp} ({lines_count} domains)")

    # Step 2: Download blocklist
    url = BASE_URL + filename
    print(f"  Downloading blocklist...")

    content = fetch_url(url)
    domains = []

    for line in content.decode('utf-8').splitlines():
        domain = line.strip()
        if domain:  # Skip empty lines
            domains.append(domain)

    if not domains:
        print("  Error: Downloaded blocklist is empty", file=sys.stderr)
        sys.exit(1)

    metadata = {
        'filename': filename,
        'count': len(domains),
        'lines_count': lines_count
    }

    return domains, timestamp, metadata


def parse_bon_appetit(domain: str) -> str:
    """Format domain in compact JSON YAML format."""
    return f'  - {{"name": "{domain}"}}'


## Source-Specific Functions: StevenBlack Hosts

def fetch_stevenblack() -> Tuple[List[str], str, Dict]:
    """
    Fetch StevenBlack unified hosts list.
    Returns: (domains_list, timestamp, metadata_dict)
    """
    HOSTS_URL = "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"

    # Download hosts file
    print("  Fetching hosts file...")
    content = fetch_url(HOSTS_URL)

    # Parse header for metadata
    lines = content.decode('utf-8').splitlines()
    timestamp = None
    total_entries = None
    domains = []

    for line in lines:
        line = line.strip()

        # Extract date from header
        if line.startswith('# Date:'):
            # Format: # Date: 19 December 2025 21:22:56 (UTC)
            date_str = line.replace('# Date:', '').strip()
            # Convert to ISO8601 format
            try:
                from datetime import datetime
                # Parse the date string
                date_str_clean = date_str.replace('(UTC)', '').strip()
                dt = datetime.strptime(date_str_clean, '%d %B %Y %H:%M:%S')
                timestamp = dt.strftime('%Y-%m-%dT%H:%M:%SZ')
            except Exception as e:
                print(f"  Warning: Could not parse date: {e}", file=sys.stderr)
                timestamp = date_str

        # Extract total entries count
        elif line.startswith('# Number of unique domains:'):
            match = re.search(r'# Number of unique domains:\s*([\d,]+)', line)
            if match:
                total_entries = int(match.group(1).replace(',', ''))

        # Parse domain entries (format: 0.0.0.0 domain.name)
        elif line and not line.startswith('#') and line.startswith('0.0.0.0 '):
            parts = line.split()
            if len(parts) >= 2:
                domain = parts[1].strip()
                # Skip localhost entries
                if domain not in ['localhost', 'localhost.localdomain', 'local',
                                'broadcasthost', '0.0.0.0']:
                    domains.append(domain)

    if not timestamp:
        print("  Error: Could not extract timestamp from hosts file", file=sys.stderr)
        sys.exit(1)

    if not domains:
        print("  Error: No domains found in hosts file", file=sys.stderr)
        sys.exit(1)

    print(f"  Last updated: {timestamp} ({len(domains)} domains)")

    metadata = {
        'count': len(domains),
        'total_entries': total_entries or len(domains)
    }

    return domains, timestamp, metadata


def parse_stevenblack(domain: str) -> str:
    """Format domain in compact JSON YAML format."""
    return f'  - {{\"name\": \"{domain}\"}}'


