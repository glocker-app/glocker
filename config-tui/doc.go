package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/google/renameio/v2"
	"gopkg.in/yaml.v3"

	"glocker/internal/config"
)

// generatedMarker identifies blocklist files written by update_domains.py.
// Those are shown as on/off packs; everything else included is editable.
const generatedMarker = "Generated by update_domains.py"

// File is one YAML file being edited.
type File struct {
	Path     string
	Rel      string // include path as written in the main file ("" for the main file)
	Root     *yaml.Node
	orig     []byte // bytes on disk, for the diff
	baseline []byte // encoding at load/save time, for change detection
	mode     os.FileMode
}

// Pack is a generated blocklist pulled in (or not) by an !include line.
type Pack struct {
	Rel     string
	Name    string
	Count   int
	Enabled bool
}

// DomainEntry is one editable domain, wherever it lives.
type DomainEntry struct {
	File *File
	Seq  *yaml.Node // the sequence holding Node
	Node *yaml.Node // the domain's mapping
}

type Doc struct {
	BaseDir  string
	Main     *File
	Personal []*File // editable includes; new domains go to the first
	Packs    []*Pack
}

func Load(path string) (*Doc, error) {
	main, err := loadFile(path, "")
	if err != nil {
		return nil, err
	}
	if body(main.Root).Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: top level is not a mapping", path)
	}
	d := &Doc{BaseDir: filepath.Dir(path), Main: main}
	included := map[string]bool{}
	for _, n := range d.listContent() {
		if n.Tag != includeTag {
			continue
		}
		included[filepath.Clean(n.Value)] = true
		full := filepath.Join(d.BaseDir, n.Value)
		if isGenerated(full) {
			d.Packs = append(d.Packs, newPack(full, n.Value, true))
			continue
		}
		f, err := loadFile(full, n.Value)
		if err != nil {
			return nil, err
		}
		d.Personal = append(d.Personal, f)
	}
	// Generated blocklists in conf.d/ that aren't included are disabled packs.
	matches, _ := filepath.Glob(filepath.Join(d.BaseDir, "conf.d", "*.yaml"))
	sort.Strings(matches)
	for _, full := range matches {
		rel, _ := filepath.Rel(d.BaseDir, full)
		if !included[rel] && isGenerated(full) {
			d.Packs = append(d.Packs, newPack(full, rel, false))
		}
	}
	return d, nil
}

// loadFile reads a YAML file. A missing included file starts as an empty list
// and is created on save.
func loadFile(path, rel string) (*File, error) {
	f := &File{Path: path, Rel: rel, mode: 0o644}
	data, err := os.ReadFile(path)
	switch {
	case os.IsNotExist(err) && rel != "":
		f.Root = &yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{{Kind: yaml.SequenceNode}}}
		f.baseline, _ = encode(f.Root)
		return f, nil
	case err != nil:
		return nil, err
	}
	if st, err := os.Stat(path); err == nil {
		f.mode = st.Mode().Perm()
	}
	var root yaml.Node
	if err := yaml.Unmarshal(data, &root); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if root.Kind == 0 {
		root = yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{{Kind: yaml.SequenceNode}}}
	}
	f.Root, f.orig = &root, data
	f.baseline, err = encode(f.Root)
	return f, err
}

func isGenerated(path string) bool {
	fh, err := os.Open(path)
	if err != nil {
		return false
	}
	defer fh.Close()
	head := make([]byte, 1024)
	n, _ := fh.Read(head)
	return bytes.Contains(head[:n], []byte(generatedMarker))
}

func newPack(full, rel string, enabled bool) *Pack {
	name := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(rel), "domains-"), ".yaml")
	p := &Pack{Rel: rel, Name: name, Enabled: enabled}
	if data, err := os.ReadFile(full); err == nil {
		p.Count = bytes.Count(data, []byte("\n  - ")) + bytes.Count(data, []byte("\n- "))
	}
	return p
}

func encode(n *yaml.Node) ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(n); err != nil {
		return nil, err
	}
	err := enc.Close()
	return buf.Bytes(), err
}

func (d *Doc) cfg() *yaml.Node { return body(d.Main.Root) }

// domainList is domains.list in the main file, created if absent.
func (d *Doc) domainList() *yaml.Node {
	return ensure(ensure(d.cfg(), "domains", yaml.MappingNode), "list", yaml.SequenceNode)
}

// listContent reads domains.list without creating it.
func (d *Doc) listContent() []*yaml.Node {
	if l := path(d.cfg(), "domains", "list"); l != nil {
		return l.Content
	}
	return nil
}

func (d *Doc) Domains() []DomainEntry {
	var out []DomainEntry
	list := path(d.cfg(), "domains", "list")
	for _, n := range d.listContent() {
		if n.Kind == yaml.MappingNode {
			out = append(out, DomainEntry{d.Main, list, n})
		}
	}
	for _, f := range d.Personal {
		seq := body(f.Root)
		for _, n := range seq.Content {
			if n.Kind == yaml.MappingNode {
				out = append(out, DomainEntry{f, seq, n})
			}
		}
	}
	return out
}

func (d *Doc) AddDomain(name string) DomainEntry {
	f, seq := d.Main, d.domainList()
	if len(d.Personal) > 0 {
		f, seq = d.Personal[0], body(d.Personal[0].Root)
	}
	n := &yaml.Node{Kind: yaml.MappingNode}
	mapSet(n, "name", strNode(name))
	seq.Style = 0
	seq.Content = append(seq.Content, n)
	return DomainEntry{f, seq, n}
}

func (e DomainEntry) Delete() {
	if i := indexOf(e.Seq, e.Node); i >= 0 {
		removeAt(e.Seq, i)
	}
}

func (d *Doc) TogglePack(p *Pack) {
	list := d.domainList()
	if p.Enabled {
		for i, n := range list.Content {
			if n.Tag == includeTag && filepath.Clean(n.Value) == p.Rel {
				removeAt(list, i)
				break
			}
		}
	} else {
		list.Content = append(list.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: includeTag, Value: p.Rel})
	}
	p.Enabled = !p.Enabled
}

func (d *Doc) files() []*File { return append([]*File{d.Main}, d.Personal...) }

// Change is a file whose content differs from what was loaded.
type Change struct {
	File *File
	New  []byte // what gets written: the edit replayed onto the original text
	enc  []byte // the plain re-encoding, the next baseline
}

func (d *Doc) Changes() ([]Change, error) {
	var out []Change
	for _, f := range d.files() {
		b, err := encode(f.Root)
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(b, f.baseline) {
			out = append(out, Change{f, preserve(f.orig, f.baseline, b), b})
		}
	}
	return out, nil
}

// Validate runs glocker's own parser and validator over the edited config.
// Editable includes are inlined; generated packs are left out since they're
// large and machine-written.
func (d *Doc) Validate() error {
	root := clone(d.Main.Root)
	list := path(body(root), "domains", "list")
	if list != nil {
		var items []*yaml.Node
		for _, n := range list.Content {
			if n.Tag != includeTag {
				items = append(items, n)
				continue
			}
			for _, f := range d.Personal {
				if f.Rel == n.Value {
					items = append(items, clone(body(f.Root)).Content...)
				}
			}
		}
		list.Content = items
	}
	data, err := encode(root)
	if err != nil {
		return err
	}
	cfg, err := config.ParseConfig(data, d.BaseDir)
	if err != nil {
		return err
	}
	return config.ValidateConfig(cfg)
}

// Write saves each change atomically, to path+suffix or in place if suffix is "".
func (d *Doc) Write(changes []Change, suffix string) ([]string, error) {
	var written []string
	for _, c := range changes {
		dst := c.File.Path + suffix
		if err := renameio.WriteFile(dst, c.New, c.File.mode); err != nil {
			return written, err
		}
		c.File.orig, c.File.baseline = c.New, c.enc
		written = append(written, dst)
	}
	return written, nil
}
