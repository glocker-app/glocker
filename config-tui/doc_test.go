func TestDeleteLastWindowDropsKey(t *testing.T) {
	d, err := Load(setup(t, true))
	must(t, err)
	e := d.Domains()[0]
	setWindow(e.Node, "block_windows", -1, config.TimeWindow{Start: "09:00", End: "10:00", Days: []string{"Mon"}})
	delWindow(e.Node, "block_windows", 0)
	if mapGet(e.Node, "block_windows") != nil {
		t.Error("block_windows should be gone")
	}
}

func TestSampleEditIsMinimal(t *testing.T) {
	data, err := os.ReadFile("../conf/conf.yaml.sample")
	must(t, err)
	p := filepath.Join(t.TempDir(), "conf.yaml")
	must(t, os.WriteFile(p, data, 0o644))
	d, err := Load(p)
	must(t, err)
	unb := path(d.cfg(), "domains", "unblocking")
	mapSet(unb, "max_per_day", intNode(3))
	ch, err := d.Changes()
	must(t, err)
	if len(ch) != 1 {
		t.Fatalf("changes = %d", len(ch))
	}
	a, b := splitLines(data), splitLines(ch[0].New)
	if len(a) != len(b) {
		t.Fatalf("line count %d -> %d", len(a), len(b))
	}
	var diffs []string
	for i := range a {
		if a[i] != b[i] {
			diffs = append(diffs, b[i])
		}
	}
	if len(diffs) != 1 || !strings.Contains(diffs[0], "max_per_day: 3") {
		t.Errorf("diffs = %q", diffs)
	}
}
